/**
 * Regenerates lib/uae-emirates.ts — the seven emirates as SVG paths for the
 * homepage "Where we build" map.
 *
 * Source: Natural Earth 10m admin-1 boundaries (public domain), fetched from
 * the natural-earth-vector GitHub mirror. Projection: equirectangular scaled
 * for the UAE's mid-latitude, 1000 units wide. Rings under 45 px² are dropped
 * (specks), the rest simplified with Douglas-Peucker at ~1.1 px.
 *
 *   node scripts/build-uae-emirates.mjs
 */
import { writeFileSync, mkdtempSync } from "node:fs"
import { join } from "node:path"
import { tmpdir } from "node:os"

const SRC = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_1_states_provinces.geojson"
const META = {
  "AE-AZ": ["AZ", "Abu Dhabi"], "AE-DU": ["DU", "Dubai"], "AE-SH": ["SH", "Sharjah"], "AE-AJ": ["AJ", "Ajman"],
  "AE-UQ": ["UQ", "Umm Al Quwain"], "AE-RK": ["RK", "Ras Al Khaimah"], "AE-FU": ["FU", "Fujairah"],
  "AE-X01~": ["NZ1", "Neutral zone"], "AE-X02~": ["NZ2", "Neutral zone"],
}

console.log("fetching Natural Earth admin-1 (≈40 MB)…")
const all = await (await fetch(SRC)).json()
const uae = all.features.filter((f) => f.properties.adm0_a3 === "ARE" && META[f.properties.iso_3166_2])
if (uae.length < 7) throw new Error(`expected the 7 emirates, got ${uae.length}`)

const rings = (f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates)
let minLon = 1e9, maxLon = -1e9, minLat = 1e9, maxLat = -1e9
for (const f of uae) for (const poly of rings(f)) for (const [x, y] of poly[0]) {
  minLon = Math.min(minLon, x); maxLon = Math.max(maxLon, x); minLat = Math.min(minLat, y); maxLat = Math.max(maxLat, y)
}
const cosm = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180)
const W = 1000, S = W / ((maxLon - minLon) * cosm), H = Math.round((maxLat - minLat) * S)
const P = ([lon, lat]) => [(lon - minLon) * cosm * S, (maxLat - lat) * S]

const sq = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2
const dSeg = (p, a, b) => {
  const l2 = sq(a, b); if (l2 === 0) return sq(p, a)
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * (b[0] - a[0]) + (p[1] - a[1]) * (b[1] - a[1])) / l2))
  return sq(p, [a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])])
}
function simplify(pts, eps) {
  if (pts.length < 4) return pts
  const keep = new Array(pts.length).fill(false); keep[0] = keep[pts.length - 1] = true
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [s, e] = stack.pop(); let idx = -1, max = 0
    for (let i = s + 1; i < e; i++) { const d = dSeg(pts[i], pts[s], pts[e]); if (d > max) { max = d; idx = i } }
    if (max > eps * eps) { keep[idx] = true; stack.push([s, idx], [idx, e]) }
  }
  return pts.filter((_, i) => keep[i])
}
const area = (pts) => { let a = 0; for (let i = 0; i < pts.length - 1; i++) a += pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1]; return Math.abs(a) / 2 }
const centroid = (pts) => {
  let a = 0, cx = 0, cy = 0
  for (let i = 0; i < pts.length - 1; i++) { const c = pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1]; a += c; cx += (pts[i][0] + pts[i + 1][0]) * c; cy += (pts[i][1] + pts[i + 1][1]) * c }
  a /= 2; return [cx / (6 * a), cy / (6 * a)]
}

const out = []
for (const f of uae) {
  const [code, name] = META[f.properties.iso_3166_2]
  const parts = []; let big = null, bigA = 0
  for (const poly of rings(f)) {
    const outer = poly[0].map(P); const a = area(outer); if (a < 45) continue
    const simp = simplify(outer, 1.1); if (simp.length < 4) continue
    parts.push(simp); if (a > bigA) { bigA = a; big = simp }
  }
  const d = parts.map((pts) => "M" + pts.map((p) => p[0].toFixed(1) + " " + p[1].toFixed(1)).join("L") + "Z").join("")
  const [cx, cy] = centroid(big)
  out.push({ code, name, d, cx: +cx.toFixed(1), cy: +cy.toFixed(1), area: bigA })
}
out.sort((a, b) => b.area - a.area)

const ts = `/**
 * The seven emirates (plus two small neutral zones) as SVG paths, projected
 * from Natural Earth 10m admin-1 boundaries (public domain) with an
 * equirectangular projection scaled for 24°N and simplified to ~1px at a
 * 1000px width. Generated by scripts/build-uae-emirates.mjs; regenerate
 * rather than hand-edit.
 */
export const UAE_VIEWBOX = "0 0 ${W} ${H}"

export type EmiratePath = {
  /** Two-letter code from ISO 3166-2 (AE-DU → DU); NZ1/NZ2 are neutral zones. */
  code: string
  name: string
  d: string
  /** Centroid of the largest ring, in viewBox units — where the label sits. */
  cx: number
  cy: number
}

export const UAE_EMIRATES: EmiratePath[] = ${JSON.stringify(out.map(({ code, name, d, cx, cy }) => ({ code, name, d, cx, cy })), null, 2)}
`
writeFileSync("lib/uae-emirates.ts", ts)
console.log(`wrote lib/uae-emirates.ts (${out.length} shapes, viewBox 0 0 ${W} ${H})`)
